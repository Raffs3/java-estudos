public class VariaveisExemplos {
    public static void main(String[] args) {
        //Variáveis em formas de texto são String;
        String variavel1 = "Ordem e Progresso";

        //Variáveis simples sem casas decimais;
        int variavel2 = 8;

        //Variáveis com casas decimais;
        double variavel3 = 50.00;

        //Variáveis lógicas com verdadeiro ou falso;
        boolean variavel4 = true;

        //Variáveis lógicas com números inteiros de -128 a 127;
        byte variavel5 = 5;

        //Variáveis lógicas com números inteiros de -32.768 a 32.767;
        short variavel6 = 38;

        //Variáveis lógicas com números longos;
        long variavel7 = 1000000000;

        //Variáveis lógicas único caracter Unicode;
        char variavel8 = 'M';

        //Variáveis com números de ponto flutuante;
        float variavel9 = 35;


        //Imprimindo os valores.
        System.out.println(variavel1);
        System.out.println(variavel2);
        System.out.println(variavel3);
        System.out.println(variavel4);
        System.out.println(variavel5);
        System.out.println(variavel6);
        System.out.println(variavel7);
        System.out.println(variavel8);
        System.out.println(variavel9);
    }
}