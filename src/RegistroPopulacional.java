public class RegistroPopulacional {
    public static void main(String[] args) {
        int populacaoCidade = 200;
        long populacaoMundial = 83440000000L;
        double taxaNatalidade = 1.46;
        char continente = 'E';

        System.out.println("População de uma cidade: " + populacaoCidade);
        System.out.println("População mundial atual: " + populacaoMundial + " de pessoas");
        System.out.println("Taxa de natalidade: " + taxaNatalidade);
        System.out.println("Continente: " + continente + "--> Europa");
    }
}